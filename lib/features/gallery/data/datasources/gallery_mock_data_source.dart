  Future<PixabayResponse> fetchImages({
    required int page,
    int perPage = 20,
    String? query,
    String? category,
  }) async {
    // Simulate real network latency (300ms) for realistic loading states
    await Future.delayed(const Duration(milliseconds: 300));

    var filtered = List<PixabayImage>.from(_allMockImages);

    // Apply category filter
    if (category != null && category.isNotEmpty && category.toLowerCase() != 'all') {
      filtered = filtered.where((img) {
        return img.tags.any((tag) => tag.toLowerCase() == category.toLowerCase());
      }).toList();
    }

    // Apply search query filter
    if (query != null && query.trim().isNotEmpty) {
      final q = query.trim().toLowerCase();
      filtered = filtered.where((img) {
        final matchesUser = img.user.toLowerCase().contains(q);
        final matchesTags = img.tags.any((tag) => tag.toLowerCase().contains(q));
        return matchesUser || matchesTags;
      }).toList();
    }

    // If query has no matches, return empty response
    if (filtered.isEmpty) {
      return const PixabayResponse(total: 0, totalHits: 0, hits: []);
    }

    // Generate simulated pagination by looping items if needed
    final totalHits = max(filtered.length * 3, 50); // Provide at least 3 pages of infinite scroll!
    final startIndex = (page - 1) * perPage;

    if (startIndex >= totalHits) {
      return PixabayResponse(total: totalHits, totalHits: totalHits, hits: []);
    }

    // Wrap items to simulate infinite pagination
    final pageItems = <PixabayImage>[];
    for (int i = 0; i < perPage; i++) {
      final overallIndex = startIndex + i;
      if (overallIndex >= totalHits) break;

      final sourceItem = filtered[overallIndex % filtered.length];
      // Generate unique ID per page iteration to avoid ID collisions in list
      final uniqueId = sourceItem.id + (overallIndex ~/ filtered.length) * 1000;
      pageItems.add(
        PixabayImage(
          id: uniqueId,
          pageURL: sourceItem.pageURL,
          type: sourceItem.type,
          tags: sourceItem.tags,
          previewURL: sourceItem.previewURL,
          previewWidth: sourceItem.previewWidth,
          previewHeight: sourceItem.previewHeight,
          webformatURL: sourceItem.webformatURL,
          webformatWidth: sourceItem.webformatWidth,
          webformatHeight: sourceItem.webformatHeight,
          largeImageURL: sourceItem.largeImageURL,
          imageWidth: sourceItem.imageWidth,
          imageHeight: sourceItem.imageHeight,
          imageSize: sourceItem.imageSize,
          views: sourceItem.views + overallIndex * 25,
          downloads: sourceItem.downloads + overallIndex * 10,
          likes: sourceItem.likes + overallIndex * 5,
          comments: sourceItem.comments,
          userId: sourceItem.userId,
          user: sourceItem.user,
          userImageURL: sourceItem.userImageURL,
        ),
      );
    }

    return PixabayResponse(
      total: totalHits,
      totalHits: totalHits,
      hits: pageItems,
    );
  }
